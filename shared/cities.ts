export function bboxOf(city: City): [south: number, west: number, north: number, east: number] {
  const dLat = city.radiusKm / 111.32;
  const dLon = city.radiusKm / (111.32 * Math.cos((city.lat * Math.PI) / 180));
  return [city.lat - dLat, city.lon - dLon, city.lat + dLat, city.lon + dLon];
}

